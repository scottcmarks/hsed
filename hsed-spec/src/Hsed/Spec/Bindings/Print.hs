Maintainer  : scott@magnolia-heights.com
Stability   : experimental

@hsedc bind@ prints every parsed payload into @hsed-spec/bindings/Hsed/Bindings/\<Spec\>.hs@
(design section 3.3), built from the smart constructors of "Hsed.Spec.DSL":

@
{-# LINE 1 "core-2.01.pdf#page=107&T75" #-}
b_core_T75 :: Bound
b_core_T75 = at (anchor \@'TypeRow "core-2.01" "T75" "0\/1429" 107) (erratum scott ["Fractoin" ~> "Fraction"] typeRow)
@

The LINE pragma makes GHC cite the PDF page in any type error, so that
@stack test hsed-spec:bindings@ is the type check of every comment. The
printer is pure and total except for a binding whose shape the rules have
not resolved yet ('Hsed.Spec.DSL.PolyBinding'), which it reports.
-}
module Hsed.Spec.Bindings.Print
  ( Entry
  , printBindingsModule
  , moduleNameFor
  , bindingIdent
  , specPrefix
  ) where

import qualified Data.Text         as DT
import qualified RIO.Char          as C
import qualified RIO.Text          as T
import           RIO

import           Hsed.Spec.Anchor  (AnchorId, anchorIdent, locationText, renderAnchorId)
import           Hsed.Spec.Common  (Finding (Finding), Severity (..), SpecId (..))
import           Hsed.Spec.DSL     (SomeBinding, someBindingShape)
import           Hsed.Spec.Grammar (haskellString, printSomeBinding)
import           Hsed.Spec.IR      (StructPath (..))
import           Hsed.Spec.Shape   (shapeName)


-- | One anchor to print: its spec, id, 1-based PDF page, structure path and binding.
type Entry = (SpecId, AnchorId, Int, StructPath, SomeBinding)

-- | The letters of a spec id: @core@ for @core-2.01@.
specPrefix :: SpecId -> Text
specPrefix = T.toLower . T.takeWhile C.isAlpha . specIdText

-- | @Hsed.Bindings.Core@ for @core-2.01@.
moduleNameFor :: SpecId -> Text
moduleNameFor sid = "Hsed.Bindings." <> capitalise (specPrefix sid)
  where capitalise t = maybe t (\(c, cs) -> T.cons (C.toUpper c) cs) (T.uncons t)

-- | @b_core_T75@, @b_core_5_1_3@, @b_core_doc@.
bindingIdent :: SpecId -> AnchorId -> Text
bindingIdent sid anchorId = "b_" <> specPrefix sid <> "_" <> anchorIdent anchorId

-- | The text of the generated module for one specification.
printBindingsModule :: SpecId -> [Entry] -> Either Finding Text
printBindingsModule sid entries = do
  decls <- traverse declaration entries
  let path    = DT.replace "." "/" (moduleNameFor sid) <> ".hs"
      header  =
        [ "-- generated by hsedc bind; do not edit"
        , "{-# LANGUAGE DataKinds         #-}"
        , "{-# LANGUAGE OverloadedStrings #-}"
        , "{-# LANGUAGE TypeApplications  #-}"
        , "-- | The bindings read from the annotated " <> specIdText sid <> " specification."
        , "module " <> moduleNameFor sid <> " (bindings) where"
        , ""
        , "import Hsed.Spec.DSL"
        , "" ]
      body    = concat decls
      -- the pragma names the line that follows it, so the trailer counts
      -- itself: header, body, the pragma line, then the trailer's first line
      trailer =
        [ "{-# LINE " <> tshow (length header + length body + 2) <> " " <> haskellString path <> " #-}"
        , "bindings :: [Bound]"
        , "bindings =" ]
        <> indented [ bindingIdent s a | (s, a, _, _, _) <- entries ]
  pure (T.unlines (header <> body <> trailer))
  where
    indented [] = ["  []"]
    indented (x : xs) = ("  [ " <> x) : map ("  , " <>) xs <> ["  ]"]

-- | The pragma, signature and definition of one anchor, and a blank line.
declaration :: Entry -> Either Finding [Text]
declaration (sid, anchorId, page, StructPath struct, sb) = case someBindingShape sb of
  Nothing -> Left (Finding Error "E-SHAPE" (Just sid) (Just (renderAnchorId anchorId)) (Just page)
    ("the shape of " <> printSomeBinding sb <> " comes from its target; resolve it before printing"))
  Just shape -> Right
    [ "{-# LINE 1 " <> haskellString location <> " #-}"
    , ident <> " :: Bound"
    , ident <> " = at (anchor @'" <> shapeName shape <> " " <> haskellString (specIdText sid)
        <> " " <> haskellString (renderAnchorId anchorId) <> " " <> haskellString struct
        <> " " <> tshow page <> ") " <> operand
    , "" ]
  where
    ident    = bindingIdent sid anchorId
    location = locationText sid page anchorId
    printed  = printSomeBinding sb
    operand
      | T.any C.isSpace printed = "(" <> printed <> ")"
      | otherwise               = printed
