The layouts the @byteGrid@ rule generates from Core 2.01's byte grids
(@Hsed.Gen.Core.Layouts@) at run time: each tiles its bytes; their sizes are
what the PDF prints (Table 17 ComPacket Format, PDF 40, bytes 0-19; Table 18
Packet Format, PDF 41-42, 0-23; Table 20 Data SubPacket Format, PDF 44, 0-11;
Table 39 Level 0 Discovery Header Format, PDF 68, 0-47); their fields lie
where sedutil's structures put them (@Common/DtaStructures.h@ lines 69-75,
419-443); Table 39's versions are pinned (3.3.6.2.2 and 3.3.6.2.3, PDF 68);
and Table 212's GUDID places its 4-bit NAA, 24-bit IEEE company ID and 36-bit
vendor-specific identifier across bytes 4-11 (PDF 230).
-}
module Hsed.Gen.Core.LayoutsSpec (spec) where

import qualified RIO.ByteString        as B
import           RIO
import           Test.Hspec

import           Hsed.Core.Layout      (Field (..), Layout (..), LayoutError (..), tiles)
import           Hsed.Core.Record      (DecodedRecord (..), decodeRecord, decodeRecordStrict, encodeRecord)
import           Hsed.Gen.Core.Layouts


-- | Each field as its name, its first byte and its bytes.
bytesOf :: Layout -> [(Text, Int, Int)]
bytesOf l = [ (fieldName f, fieldStart f `div` 8, fieldWidth f `div` 8) | f <- layoutFields l ]

spec :: Spec
spec = describe "Hsed.Gen.Core.Layouts" $ do
  let layouts = [ comPacketLayout, packetLayout, dataSubPacketLayout, creditControlSubpacketLayout, level0DiscoveryResponseDataLayout
                , level0DiscoveryHeaderLayout, featureDescriptorTemplateLayout, commonSSCInformationLayout, gudidColumnContentsDescriptionLayout ]
  it "every layout of a Core byte grid tiles its bytes" $
    [ (layoutName l, tiles l) | l <- layouts ] `shouldBe` [ (layoutName l, True) | l <- layouts ]
  it "gives the ComPacket header 20 bytes, the packet header 24, the subpacket header 12, the Level 0 Discovery header 48" $
    map layoutSize [comPacketLayout, packetLayout, dataSubPacketLayout, level0DiscoveryHeaderLayout] `shouldBe` [20, 24, 12, 48]
  it "places the headers' fields where sedutil's structures have them" $ do
    -- DtaStructures.h:419-425 DTA_ComPacketHeader: reserved0, extendedComID[4] (the ComID and its extension),
    -- outstandingData, minTransfer, length (uint32 each)
    bytesOf comPacketLayout `shouldBe`
      [("Reserved", 0, 4), ("ComID", 4, 2), ("ComID Extension", 6, 2), ("OutstandingData", 8, 4), ("MinTransfer", 12, 4), ("Length", 16, 4)]
    -- DtaStructures.h:428-436 DTA_PacketHeader: TSN and HSN (uint32 each, the Session), seqNumber, reserved0 (uint16),
    -- ackType (uint16), acknowledgement, length
    bytesOf packetLayout `shouldBe`
      [("Session", 0, 8), ("SeqNumber", 8, 4), ("Reserved", 12, 2), ("AckType", 14, 2), ("Acknowledgement", 16, 4), ("Length", 20, 4)]
    -- DtaStructures.h:439-443 DTA_DataSubPacketHeader: reserved0[6], kind (uint16), length (uint32)
    bytesOf dataSubPacketLayout `shouldBe` [("Reserved", 0, 6), ("Kind", 6, 2), ("Length", 8, 4)]
    -- DtaStructures.h:69-75 Discovery0Header: length, revision (the major and minor versions), reserved01 and
    -- reserved02 (bytes 8-15), vendorSpecific[8] (uint32 each)
    bytesOf level0DiscoveryHeaderLayout `shouldBe`
      [ ("Length of Parameter Data", 0, 4), ("Data Structure Major Version", 4, 2), ("Data Structure Minor Version", 6, 2)
      , ("Reserved", 8, 8), ("Vendor Unique", 16, 32) ]
  it "reads a Level 0 Discovery header of version 0.1, and holds a TPer to it" $ do
    let header = "\x00\x00\x00\xa0" <> "\x00\x00\x00\x01" <> B.replicate 8 0 <> B.replicate 32 0x5a
        other = B.take 6 header <> "\x00\x02" <> B.drop 8 header
    decodeRecord header `shouldBe` Right (DecodedRecord (Level0DiscoveryHeader 0xa0 (B.replicate 32 0x5a)) [] "")
    (drRecord <$> (decodeRecordStrict other :: Either LayoutError (DecodedRecord Level0DiscoveryHeader)))
      `shouldBe` Left (PinViolated "Data Structure Minor Version" 1 2)
    encodeRecord (Level0DiscoveryHeader 0xa0 (B.replicate 32 0x5a)) `shouldBe` Right header
  it "writes a GUDID as the NAA IEEE Registered format: its four constant bytes, NAA 5, the company ID and the identifier" $ do
    let gudid = GUDIDColumnContentsDescription 0x123456 0x789abcdef
    encodeRecord gudid `shouldBe` Right "\x02\x23\x00\x08\x51\x23\x45\x67\x89\xab\xcd\xef"
    decodeRecord "\x02\x23\x00\x08\x51\x23\x45\x67\x89\xab\xcd\xef" `shouldBe` Right (DecodedRecord gudid [] "")
